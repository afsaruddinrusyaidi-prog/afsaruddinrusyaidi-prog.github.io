export const LEGAL_DOCS: Record<Locale, LegalDoc[]> = {
  en: [PRIVACY_EN, COOKIES_EN, TERMS_EN],
  ms: [PRIVACY_MS, COOKIES_MS, TERMS_MS],
}

export function getLegalDoc(slug: LegalDoc["slug"], locale: Locale): LegalDoc {
  const doc = LEGAL_DOCS[locale].find((d) => d.slug === slug)
  if (!doc) throw new Error(`Unknown legal document: ${slug}`)
  return doc
}
