/**
 * Legal document content, in English and Bahasa Malaysia.
 *
 * Section 7(2) of the Personal Data Protection Act 2010 requires the personal
 * data protection notice to be issued in both the national language and
 * English, so every document here carries both and the page offers a toggle
 * rather than separate routes — one URL to share, no risk of one language
 * quietly falling out of date behind the other.
 *
 * These documents describe the site as it actually behaves. The claims about
 * cookies and tracking were verified against the live site: no Set-Cookie
 * header is returned on any route, no analytics or pixel is loaded, and fonts
 * are self-hosted rather than fetched from a third-party CDN. If any of that
 * changes, this file changes in the same commit.
 */

